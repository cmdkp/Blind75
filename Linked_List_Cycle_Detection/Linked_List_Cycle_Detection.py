# Definition for singly-linked list.
# class ListNode:
#     def __init__(self, val=0, next=None):
#         self.val = val
#         self.next = next

class Solution:
    def hasCycle(self, head: Optional[ListNode]) -> bool:

        curr = head
        while curr:
            if not curr.val:
                return True
            
            curr.val = None
            
            if not curr.next:
                return False
                
            curr = curr.next

        return False
        

